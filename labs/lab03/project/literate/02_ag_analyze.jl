# # Визуализация и анализ графа атак
#
# **Цель:** представить построенный граф атак и выделить вершины,
# занимающие важное положение по входящей степени и PageRank.
#
# Анализ выполняется для сохранённого базового эксперимента, чтобы
# изображение графа и численные показатели относились к одной модели.
#
# ## Активация проекта и загрузка библиотек
#
# GraphRecipes строит изображение графа, Plots задаёт оформление,
# а JLD2 загружает результаты. Общие функции модели подключаются
# из каталога исходного кода проекта.

using DrWatson
@quickactivate "project"

using Graphs, JLD2, Plots, GraphRecipes

include(srcdir("attack_graph.jl"))

# ## Загрузка результатов базового эксперимента
#
# Используем тот же набор параметров и тот же способ построения имени,
# что и в первом эксперименте. Перед анализом необходимо выполнить
# базовый эксперимент и получить файл с графом и метриками.

include(srcdir("experiment_params.jl"))
params = deepcopy(experiment_params)
filename = datadir("attack_graph", savename(params, "jld2"))
isfile(filename) || error("Сначала выполните базовый эксперимент: файл $filename не найден.")
@load filename data

g = data[:graph]
metrics = data[:metrics]

# ## Нормализация PageRank для цветовой шкалы
#
# PageRank учитывает входящие связи и значимость вершин, из которых
# они исходят. Чтобы сопоставить значениям цвета, приведём их к отрезку
# от 0 до 1 с помощью преобразования
#
# $$r_i^*=\frac{r_i-r_{\min}}{r_{\max}-r_{\min}}.$$
#
# Если все значения одинаковы, знаменатель равен нулю. В этом случае
# всем вершинам назначается середина цветовой шкалы — значение 0.5.
# Нормализация применяется только для визуализации, исходные метрики
# в сохранённом результате остаются доступными для анализа.

pagerank = metrics[:pagerank]
min_rank, max_rank = extrema(pagerank)

norm_rank = if max_rank == min_rank
    fill(0.5, length(pagerank))
else
    (pagerank .- min_rank) ./ (max_rank - min_rank)
end

colors = [cgrad(:RdYlGn, rev=true)[norm_rank[i]] for i = 1:nv(g)]

# ## Построение и сохранение графа атак
#
# Метки показывают номера вершин, а цвет отражает их PageRank.
# Расположение вершин служит для удобства чтения и не обозначает
# физическое расстояние или стоимость перехода между узлами сети.

attack_plot = graphplot(
    g,
    nodeshape=:circle,
    curves=false,
    linecolor=:black,
    nodecolor=colors,
    nodelabel=1:nv(g),
    title="Граф атак (цвет = PageRank)",
    size=(800, 600),
)

mkpath(plotsdir())
savefig(attack_plot, plotsdir("attack_graph.png"))
println("График сохранён в ", plotsdir("attack_graph.png"))

# Выведем объект графика отдельным блоком, чтобы изображение появилось
# при выполнении документа Quarto или ячеек Jupyter notebook.

display(attack_plot)

# ## Структурные характеристики и длины путей
#
# Число вершин и рёбер описывает размер модели, а число найденных путей —
# количество простых маршрутов от источника к цели.
# В текущем представлении путь хранится как список вершин, поэтому
# `length(path)` считает вершины; число переходов на единицу меньше.
# Вместо вывода всех длин приведём их диапазон, чтобы большой набор
# маршрутов не перегружал отчёт.

println("=== Анализ графа атак ===")
println("Количество узлов: ", nv(g))
println("Количество рёбер: ", ne(g))
println(
    "Количество путей от ",
    params[:source],
    " к ",
    params[:target],
    ": ",
    length(data[:paths]),
)

if !isempty(data[:paths])
    path_lengths = length.(data[:paths])
    println("Длина пути в вершинах: от ", minimum(path_lengths), " до ", maximum(path_lengths))
    println("Наиболее вероятный путь: ", data[:likely_path])
else
    println("Цель недостижима из выбранного источника.")
end

# ## Вершины с наибольшей входящей степенью
#
# Входящая степень — количество рёбер, ведущих в вершину.
# Высокое значение указывает на множество непосредственных подходов
# к узлу, но не учитывает вероятности переходов и доступность этих
# подходов из выбранного источника атаки.

println("\nТоп-5 узлов по in-degree:")
top_indeg = sortperm(metrics[:in_degree], rev=true)[1:min(5, nv(g))]

for i in top_indeg
    println(" Узел $i: in-degree = $(metrics[:in_degree][i])")
end

# ## Вершины с наибольшим PageRank
#
# Сопоставим ранжирование по входящей степени с ранжированием по PageRank.
# Эти списки могут различаться: PageRank учитывает не только количество
# входящих связей, но и структуру связей во всём графе.

println("\nТоп-5 узлов по PageRank:")
top_pr = sortperm(metrics[:pagerank], rev=true)[1:min(5, nv(g))]

for i in top_pr
    println(" Узел $i: PageRank = $(round(metrics[:pagerank][i], digits=4))")
end

