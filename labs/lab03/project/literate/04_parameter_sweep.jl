# # Параметрический эксперимент
#
# **Цель:** исследовать влияние вероятности появления ребра на число
# путей атаки, максимальную входящую степень и среднюю длину маршрута.
#
# Число узлов и положения источника и цели фиксируются. Изменяется
# параметр случайной топологии, что позволяет сравнить модели сетей
# с разной ожидаемой плотностью связей.
#
# ## Подготовка проекта и библиотек
#
# DataFrames и CSV используются для табличного представления результатов,
# Statistics — для вычисления среднего, Plots — для построения графиков.

using DrWatson
@quickactivate "project"

using Graphs, Random, CSV, DataFrames, Plots, StatsBase, Statistics

include(srcdir("attack_graph.jl"))

# ## Диапазон параметров
#
# Вероятность появления направленного ребра изменяется от 0.1 до 0.9
# с шагом 0.1. Модель содержит 13 вершин, источник — вершина 1,
# цель — вершина 13. Таким образом, обе вершины существуют в графе.
#
# Параметр $p$ задаёт вероятность включения ребра, а не вероятность
# успешной атаки. Для графа без петель и дополнительных доверительных
# связей ожидаемое число рёбер равно
#
# $$\mathbb{E}[|E|]=p\,n(n-1).$$
#
# Реальная плотность конкретного графа может отличаться от $p$.
# При больших значениях $p$ полный перебор путей даже для 13 вершин
# может требовать значительных времени и памяти.

edge_probs = 0.1:0.1:0.9
n_nodes = 13
source = 1
target = n_nodes

# ## Подготовка результатов и генератора случайных чисел
#
# Для каждой точки сохраняется набор показателей. Фиксированное
# начальное состояние генератора позволяет повторить последовательность
# графов при одинаковом программном окружении.

results = []
Random.seed!(123)

# ## Серия вычислительных экспериментов
#
# Для каждого значения $p$ строится новый граф и перечисляются простые
# пути к цели. Дополнительно вычисляется максимальная входящая степень.
#
# Средняя длина рассчитывается как среднее число вершин в найденных
# маршрутах. Если нужна длина в переходах, из каждой длины следует
# вычесть единицу. При отсутствии путей в таблицу записывается 0:
# это условный признак отсутствия маршрутов, а не длина существующего пути.

for p in edge_probs
    println("Плотность рёбер: $p")
    g = build_attack_graph(n_nodes, p, Dict(), [])
    paths = find_all_paths(g, source, target)
    metrics = compute_centrality_metrics(g)
    max_indeg = maximum(metrics[:in_degree])
    avg_path_len = isempty(paths) ? 0.0 : mean(length.(paths))

    push!(
        results,
        (p=p, paths=length(paths), max_indeg=max_indeg, avg_len=avg_path_len),
    )
end

# ## Таблица результатов и сохранение CSV
#
# Столбец `p` содержит параметр генерации, `paths` — число путей,
# `max_indeg` — максимальную входящую степень, `avg_len` — среднюю
# длину пути в вершинах. CSV сохраняет результаты для последующего
# анализа без повторного перечисления маршрутов.

df = DataFrame(results)
mkpath(datadir("parameter_sweep"))
CSV.write(datadir("parameter_sweep", "results.csv"), df)

# Выведем таблицу в выполняемый документ, чтобы численные значения
# можно было сопоставить с изображёнными далее зависимостями.

display(df)

# ## Зависимость числа путей от вероятности появления ребра
#
# Увеличение ожидаемой плотности создаёт больше возможностей перехода
# между вершинами. На графике проверяется, как это проявилось
# в числе маршрутов для полученных случайных реализаций.

p1 = plot(
    edge_probs,
    [r.paths for r in results],
    marker=:circle,
    xlabel="Вероятность появления ребра",
    ylabel="Количество путей",
    label="Пути",
)

# ## Изменение средней длины пути
#
# Второй график показывает среднюю длину по всем простым путям,
# а не длину кратчайшего пути. При добавлении связей могут появляться
# как короткие, так и длинные маршруты, поэтому эти показатели
# нельзя интерпретировать одинаково.

p2 = plot(
    edge_probs,
    [r.avg_len for r in results],
    marker=:circle,
    xlabel="Вероятность появления ребра",
    ylabel="Средняя длина (вершины)",
    label="Средняя длина",
)

# ## Сохранение и вывод общего рисунка
#
# Объединим зависимости для совместного анализа. Явный вывод объекта
# графика позволяет увидеть результат в выполняемом Quarto-документе
# и Jupyter notebook, а PNG можно использовать как отдельную иллюстрацию.

combined = plot(p1, p2, layout=(2, 1), size=(800, 600))
mkpath(plotsdir())
savefig(combined, plotsdir("parameter_sweep.png"))
display(combined)

# ## Интерпретация результатов
#
# Эксперимент позволяет сопоставить связность сети и разнообразие
# маршрутов к целевому узлу. Для каждого значения параметра построен
# один независимый граф, поэтому отдельные колебания показателей
# не следует считать устойчивой закономерностью. Для количественной
# оценки зависимости нужны повторные реализации и оценка разброса.
# Кроме того, число путей не равно вероятности успешной атаки:
# в этой серии вероятности эксплуатации отдельных переходов не учитываются.
